/**
 * Generates components/icons/index.ts — the product's one icon module.
 *
 *   pnpm icons:generate
 *
 * Each export is an IBM Carbon glyph (components/icons/glyph.tsx;
 * docs/ui/UI-03-nesto-theme.md §6), copied from @carbon/icons (Apache-2.0, a
 * dev dependency) at its 32-unit size, so the product ships only the glyphs it
 * uses and no icon package.
 *
 * To add an icon: add its name and the Carbon name to icon-map.mjs, then run
 * this, and import it from "@/components/icons" (tests/architecture/icons.test.ts).
 */
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";

import { CARBON_FOR } from "./icon-map.mjs";

const require = createRequire(import.meta.url);

/** The drafting arc: a quarter-open circle, one 32nd of the box thick — 0.5px at 16px, like a drawn line. */
const SPINNER = '<path d="M16 4a12 12 0 1 1-12 12" fill="none" stroke="currentColor" stroke-width="2.25" stroke-linecap="square"/>';

const attr = (attrs) =>
  Object.entries(attrs)
    .map(([key, value]) => ` ${key}="${String(value).replace(/"/g, "&quot;")}"`)
    .join("");

function markup(node) {
  // Carbon's 32×32 transparent hit rectangle draws nothing.
  if (node.elem === "rect" && node.attrs?.fill === "none" && Number(node.attrs.width) === 32) return "";
  const inner = (node.content ?? []).map(markup).join("");
  return `<${node.elem}${attr(node.attrs ?? {})}${inner ? `>${inner}</${node.elem}>` : "/>"}`;
}

function glyph(name) {
  if (name === "SPINNER") return SPINNER;
  const icon = require(`@carbon/icons/lib/${name}/32.js`);
  const tree = icon.default ?? icon;
  if (tree.attrs?.viewBox !== "0 0 32 32") throw new Error(`${name}: unexpected viewBox ${tree.attrs?.viewBox}`);
  return tree.content.map(markup).join("");
}

const out = [
  "// Generated by scripts/icons/generate.mjs — do not edit by hand. Carbon glyphs © IBM, Apache-2.0.",
  'import { glyph } from "./glyph";',
  "",
  'export type { IconComponent, IconProps } from "./glyph";',
  "",
  ...Object.entries(CARBON_FOR).map(
    ([name, carbon]) => `export const ${name} = /* @__PURE__ */ glyph("${name}", ${JSON.stringify(glyph(carbon))});`,
  ),
  "",
];

writeFileSync(new URL("../../components/icons/index.ts", import.meta.url), out.join("\n"));
console.log(`components/icons/index.ts: ${Object.keys(CARBON_FOR).length} icons`);
