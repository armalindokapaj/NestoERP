/**
 * The widget registry (PRD #4 §18, §59).
 *
 * A widget is declared once, with the permission that gates it and the scope it
 * reads under. Widgets are never hardcoded inside a role page — there is no
 * per-role dashboard file anywhere in the codebase (PRD #4 §4, §18).
 *
 * Edge-safe: declaration only, no data access.
 */
import type { ModuleKey } from "./modules";
import type { Permission } from "./permissions";

/** Widget footprints on the dashboard grid (PRD #4 §60). */
export const WIDGET_SIZES = ["SMALL", "MEDIUM", "LARGE", "FULL"] as const;
export type WidgetSize = (typeof WIDGET_SIZES)[number];

/**
 * How a widget presents its data. Each kind has one renderer, so a new widget
 * is a configuration entry rather than a new component (PRD #4 §17).
 */
export type WidgetKind =
  | "list"
  | "breakdown"
  | "alerts"
  | "approvals"
  | "activity"
  | "progress"
  | "projects";

export type WidgetDefinition = {
  key: string;
  module: ModuleKey;
  /** Absent from the dashboard entirely when the user lacks this (PRD #4 §19). */
  permission: Permission;
  title: string;
  description?: string;
  kind: WidgetKind;
  size: WidgetSize;
  /** Lower sorts first: critical attention before performance (PRD #4 §62). */
  priority: number;
  /** Where the widget's "view all" leads (PRD #4 §21). */
  href?: string;
  emptyMessage: string;
  /**
   * The widget contract (Workspace Context §75): which workspaces the widget
   * belongs to. A group widget asks each authorised company in turn (`module`
   * and `permission` are what one company must grant for it to count) and is
   * hidden in a company workspace; a company widget is hidden in the group
   * unless it says it supports it. Defaults: company yes, group no.
   */
  supportsGroupContext?: boolean;
  supportsCompanyContext?: boolean;
};

